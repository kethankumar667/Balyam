/**
 * Inventory shipped static media and local generated audio without claiming legal clearance.
 * Run from any directory: node client/scripts/audit-asset-provenance.mjs
 */
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, extname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const output = join(root, "docs", "legal", "asset-provenance-inventory.json");
const media = new Set([".png", ".jpg", ".jpeg", ".webp", ".avif", ".svg", ".ico", ".wav", ".mp3", ".ogg", ".m4a", ".mp4", ".webm", ".woff", ".woff2", ".ttf", ".otf"]);
const audio = new Set([".wav", ".mp3", ".ogg", ".m4a"]);
const normalize = (path) => path.replace(/\\/g, "/");
const tracked = new Set(execFileSync("git", ["ls-files", "-z", "--", "client/public", "client/src/assets", "docs/brand"], { cwd: root, encoding: "utf8" }).split("\0").filter(Boolean));
const paths = new Set([...tracked].filter((path) => media.has(extname(path).toLowerCase())));

function walk(directory) {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) walk(path);
    else if (entry.isFile() && media.has(extname(path).toLowerCase())) paths.add(normalize(relative(root, path)));
  }
}
for (const directory of ["client/public", "client/src/assets", "docs/brand"]) walk(join(root, directory));

const logoNames = new Set(["Bhalyam-logo.png", "Bhalyam-logo.webp", "Bhalyam-logo.avif", "icon-192.png", "icon-512.png", "favicon-32.png", "favicon.ico", "apple-touch-icon.png"]);
function evidenceFor(path) {
  if (path.startsWith("client/public/audio/themes/") && extname(path) === ".wav") {
    return { status: "generator-documented-bytes-unverified", evidence: ["client/scripts/gen-placeholder-audio.mjs", "client/public/audio/themes/README.md"], action: "Confirm these bytes were generated by the repository script; record any replacement recording's source and licence." };
  }
  if (logoNames.has(path.slice("client/public/".length)) && path.startsWith("client/public/")) {
    return { status: "derivation-documented-rights-unverified", evidence: ["client/scripts/generate-logo-assets.mjs", "docs/brand/bhalyam-logo-master.png"], action: "Obtain the master artwork's creator/provider terms and ownership record; resizing is not rights clearance." };
  }
  if (path.startsWith("client/public/way-faces/")) {
    return { status: "derivation-documented-rights-unverified", evidence: ["client/scripts/generate-way-faces.mjs"], action: "Clear the source avatar's rights; a crop inherits the source's unresolved provenance." };
  }
  if (path.startsWith("client/public/illustrations/")) {
    return { status: "creative-brief-only-rights-unverified", evidence: ["client/public/illustrations/prompts-refined.md"], action: "Attach per-file creation/export records, provider terms or an artist licence; prompts alone do not prove origin." };
  }
  return { status: "source-and-rights-unverified", evidence: [], action: "Record creator, original source, acquisition date, commercial-use terms and any attribution/redistribution requirements." };
}

const assets = [...paths].sort().map((path) => {
  const absolute = join(root, path);
  const present = existsSync(absolute);
  const bytes = present ? readFileSync(absolute) : null;
  return {
    path,
    kind: audio.has(extname(path).toLowerCase()) ? "audio" : "visual-media",
    tracked: tracked.has(path),
    present,
    sizeBytes: bytes?.length ?? null,
    sha256: bytes ? createHash("sha256").update(bytes).digest("hex") : null,
    rightsCleared: false,
    ...evidenceFor(path),
  };
});
const counts = (key) => assets.reduce((result, item) => {
  result[item[key]] = (result[item[key]] ?? 0) + 1;
  return result;
}, {});
const html = readFileSync(join(root, "client", "index.html"), "utf8");
const fontUrl = html.match(/href="(https:\/\/fonts\.googleapis\.com\/css2[^"]+)"/)?.[1];
const geistLicensePath = "client/node_modules/@fontsource-variable/geist/LICENSE";
const geistLicense = existsSync(join(root, geistLicensePath)) ? readFileSync(join(root, geistLicensePath), "utf8") : "";
const report = {
  schemaVersion: 1,
  scope: ["client/public", "client/src/assets", "docs/brand"],
  method: "Read-only filesystem and Git inventory; SHA-256 identifies inventoried bytes, not ownership. Includes all public media, even if not referenced by the UI.",
  limitations: [
    "Not legal advice or trademark clearance. No asset is approved for commercial use by this inventory.",
    "No licence receipts, provider-account terms, artist contracts or generation/export records were supplied.",
    "Generator and derivation references document possible origins; outputs were not reproduced or byte-compared.",
    "Inline SVG/canvas/Web Audio code is outside the static-file inventory; selected examples are listed separately.",
    "No deployed bundle, runtime user uploads, external font responses or every dependency's embedded assets were inspected.",
    "Missing/untracked files and ignored local audio can differ between this checkout and deployment.",
  ],
  summary: { total: assets.length, tracked: assets.filter((a) => a.tracked).length, present: assets.filter((a) => a.present).length, byKind: counts("kind"), byEvidenceStatus: counts("status") },
  codeGeneratedExamples: [
    { path: "client/src/lib/unoCardBackArt.ts", evidence: "Sixteen closed-set SVG motif specifications; no text or embedded raster. Source presence is not authorship or legal clearance." },
    { path: "client/src/games/ludo/sound.ts", evidence: "AudioContext oscillator-based synthesis observed." },
    { path: "client/src/games/rummy/sound.ts", evidence: "AudioContext oscillator-based synthesis observed." },
    { path: "client/src/games/brainvita/brainvitaFoley.ts", evidence: "Noise-buffer and oscillator synthesis observed." },
  ],
  externalFonts: {
    stylesheetUrl: fontUrl ?? null,
    families: fontUrl ? [...fontUrl.matchAll(/(?:\?|&)family=([^:&]+)/g)].map((m) => m[1].replace(/\+/g, " ")) : [],
    status: "Per-family upstream licence and redistribution conditions not verified; being hosted by Google is not a blanket licence.",
  },
  bundledFontPackages: [{
    name: "@fontsource-variable/geist",
    importEvidence: "client/src/index.css",
    licenseEvidence: geistLicensePath,
    license: geistLicense.includes("SIL Open Font License, Version 1.1") ? "OFL-1.1" : "not-verified",
    status: "Installed package licence inspected when available; confirm copyright/licence notices accompany distributed font files. This is not a complete dependency audit.",
  }],
  assets,
};
writeFileSync(output, `${JSON.stringify(report, null, 2)}\n`);
console.log(JSON.stringify(report.summary, null, 2));
console.log(`Inventory: ${relative(root, output)}`);
