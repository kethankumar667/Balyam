-- Migration: give Google sign-ins a first and last name
--
-- The email sign-up form hands Supabase `first_name` / `last_name` itself.
-- Google sends only `full_name` / `name` (and sometimes `given_name` /
-- `family_name`), so every Google account was created with both columns null.
--
-- This replaces `handle_new_user` (last defined in 20260817000000) so a new
-- account takes the form's own names first, then Google's given/family name,
-- then a split of the full name. Everything else in the function is unchanged.
--
-- Deliberately NOT done here:
--   * avatar_id — Google's `picture` is an off-site URL and avatars are a
--     closed set the app validates; copying it would leak every player's IP.
--   * dob / gender — Google does not share them on the basic scopes; the app
--     asks the member (birthday: for the Bhalyam group's birthday wishes;
--     gender: optional).
--   * account_id (the internal Bhalyam ID) — generated by the client once
--     per member, using the birth year for the era tag when it is known.

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  meta       jsonb := coalesce(new.raw_user_meta_data, '{}'::jsonb);
  full_name  text  := nullif(
    btrim(regexp_replace(coalesce(meta ->> 'full_name', meta ->> 'name', ''), '\s+', ' ', 'g')),
    ''
  );
  first_part text  := nullif(split_part(full_name, ' ', 1), '');
  last_part  text  := nullif(btrim(substr(full_name, length(first_part) + 1)), '');
begin
  insert into public.profiles (
    id,
    email,
    first_name,
    last_name,
    display_name,
    dob,
    gender,
    account_id,
    avatar_id
  )
  values (
    new.id,
    new.email,
    coalesce(nullif(meta ->> 'first_name', ''), nullif(meta ->> 'given_name', ''), first_part),
    coalesce(nullif(meta ->> 'last_name', ''), nullif(meta ->> 'family_name', ''), last_part),
    coalesce(
      meta ->> 'display_name',
      meta ->> 'full_name',
      meta ->> 'name'
    ),
    case
      when (meta ->> 'dob') is not null and (meta ->> 'dob') ~ '^\d{4}-\d{2}-\d{2}$'
      then (meta ->> 'dob')::date
      else null
    end,
    meta ->> 'gender',
    meta ->> 'account_id',
    meta ->> 'avatar_id'
  )
  on conflict (id) do update set
    email        = coalesce(excluded.email, profiles.email),
    first_name   = coalesce(excluded.first_name, profiles.first_name),
    last_name    = coalesce(excluded.last_name, profiles.last_name),
    display_name = coalesce(excluded.display_name, profiles.display_name),
    dob          = coalesce(excluded.dob, profiles.dob),
    gender       = coalesce(excluded.gender, profiles.gender),
    account_id   = coalesce(excluded.account_id, profiles.account_id),
    avatar_id    = coalesce(excluded.avatar_id, profiles.avatar_id),
    updated_at   = now();
  return new;
end;
$$;

-- Backfill accounts that already exist. Only empty columns are filled, and
-- only from names the account itself supplied — nothing is overwritten.
with names as (
  select
    u.id,
    nullif(split_part(meta.full_name, ' ', 1), '')                                             as first_part,
    nullif(btrim(substr(meta.full_name, length(split_part(meta.full_name, ' ', 1)) + 1)), '') as last_part,
    nullif(u.raw_user_meta_data ->> 'given_name', '')                                          as given_name,
    nullif(u.raw_user_meta_data ->> 'family_name', '')                                         as family_name
  from auth.users u
  cross join lateral (
    select nullif(
      btrim(regexp_replace(
        coalesce(u.raw_user_meta_data ->> 'full_name', u.raw_user_meta_data ->> 'name', ''),
        '\s+', ' ', 'g'
      )),
      ''
    ) as full_name
  ) meta
)
update public.profiles p
set
  first_name = coalesce(p.first_name, n.given_name, n.first_part),
  last_name  = coalesce(p.last_name, n.family_name, n.last_part),
  updated_at = now()
from names n
where p.id = n.id
  and (
    (p.first_name is null and coalesce(n.given_name, n.first_part) is not null)
    or (p.last_name is null and coalesce(n.family_name, n.last_part) is not null)
  );
