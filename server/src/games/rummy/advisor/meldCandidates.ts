import type { Card, Rank } from "@shared/types.js";
import { classifyMeld } from "../melds.js";
import { RANK_INDEX, SUIT_INDEX, isWild } from "./cards.js";

export type MeldKind = "pure" | "impure" | "set";

/** One valid group inside a hand, as a bitmask over the hand's indices. */
export interface MeldCandidate {
  mask: number;
  kind: MeldKind;
}

const bit = (index: number): number => 1 << index;

/** Every way to choose `count` items from `items`, in order. */
function combinations(items: readonly number[], count: number): number[][] {
  if (count === 0) return [[]];
  const out: number[][] = [];
  const walk = (start: number, picked: number[]): void => {
    if (picked.length === count) {
      out.push(picked.slice());
      return;
    }
    for (let i = start; i < items.length; i++) {
      picked.push(items[i]);
      walk(i + 1, picked);
      picked.pop();
    }
  };
  walk(0, []);
  return out;
}

/**
 * Every valid sequence and set that can be built from the cards in `hand`.
 *
 * Generated by trying every window of a suit and every rank, filling gaps with jokers, and then asking the
 * engine's own `classifyMeld` whether the result is a legal group. The rules are therefore never restated
 * here, so this cannot drift from what the engine will accept on a declaration.
 *
 * A wild-rank card is offered both ways: in its own slot as a natural card (which keeps a run pure) and as a
 * joker standing in for any other slot.
 */
export function enumerateMelds(hand: readonly Card[], wild: Rank): MeldCandidate[] {
  const found = new Map<number, MeldKind>();

  const wildIndices = hand
    .map((card, index) => ({ card, index }))
    .filter(({ card }) => isWild(card, wild))
    .sort((a, b) => Number(!!b.card.isPrintedJoker) - Number(!!a.card.isPrintedJoker))
    .map(({ index }) => index);

  const emit = (mask: number): void => {
    if (found.has(mask)) return;
    const cards = hand.filter((_, index) => mask & bit(index));
    const meld = classifyMeld(cards, wild);
    if (!meld) return;
    found.set(mask, meld.kind === "pureSequence" ? "pure" : meld.kind === "impureSequence" ? "impure" : "set");
  };

  const emitWithJokers = (usedNaturals: number, jokersNeeded: number): void => {
    const free = wildIndices.filter((index) => !(usedNaturals & bit(index)));
    if (jokersNeeded > free.length) return;
    for (const chosen of combinations(free, jokersNeeded)) {
      emit(chosen.reduce((mask, index) => mask | bit(index), usedNaturals));
    }
  };

  /* ── Sequences: every window of every suit ── */
  const bySuitPosition: number[][][] = Array.from({ length: 4 }, () => Array.from({ length: 14 }, () => [] as number[]));
  hand.forEach((card, index) => {
    if (card.isPrintedJoker) return;
    const row = bySuitPosition[SUIT_INDEX[card.suit]];
    const rank = RANK_INDEX[card.rank];
    row[rank].push(index);
    if (rank === 0) row[13].push(index); // an Ace also stands above the King
  });

  for (let suit = 0; suit < 4; suit++) {
    const positions = bySuitPosition[suit];
    for (let start = 0; start <= 13; start++) {
      for (let end = start + 2; end <= 13 && end - start + 1 <= 13; end++) {
        let holes = 0;
        for (let p = start; p <= end; p++) if (positions[p].length === 0) holes += 1;
        if (holes > wildIndices.length) continue;

        const fill = (position: number, used: number, jokers: number, naturals: number): void => {
          if (position > end) {
            if (naturals >= 1) emitWithJokers(used, jokers);
            return;
          }
          for (const index of positions[position]) {
            if (used & bit(index)) continue;
            fill(position + 1, used | bit(index), jokers, naturals + 1);
          }
          if (jokers + 1 <= wildIndices.length) fill(position + 1, used, jokers + 1, naturals);
        };
        fill(start, 0, 0, 0);
      }
    }
  }

  /* ── Sets: one card per suit of a rank, jokers filling the rest ── */
  const byRankSuit = new Map<number, number[][]>();
  hand.forEach((card, index) => {
    if (isWild(card, wild)) return;
    const rank = RANK_INDEX[card.rank];
    const row = byRankSuit.get(rank) ?? [[], [], [], []];
    row[SUIT_INDEX[card.suit]].push(index);
    byRankSuit.set(rank, row);
  });

  for (const row of byRankSuit.values()) {
    const choose = (suit: number, used: number, size: number): void => {
      if (suit === 4) {
        if (size === 0) return;
        for (let total = Math.max(3, size); total <= 4; total++) emitWithJokers(used, total - size);
        return;
      }
      choose(suit + 1, used, size);
      for (const index of row[suit]) choose(suit + 1, used | bit(index), size + 1);
    };
    choose(0, 0, 0);
  }
  for (const total of [3, 4]) emitWithJokers(0, total);

  return [...found].map(([mask, kind]) => ({ mask, kind }));
}
